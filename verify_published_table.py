"""Check manuscript-table scope and counts against graph inputs and C++ methods.

This validates row metadata and cycle counts. Timing columns are the frozen,
rounded manuscript values; they are not regenerated by this check.
"""
import argparse
import csv
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent
CSV = ROOT / "published_table.csv"
EXPECTED_GIRTH_GRAPHS = {
    "A16c", "A128c", "A128r", "B128c", "C128c", "C128r",
    "R1200", "R2400", "D16c", "P1200", "P1600", "Q410", "Q412",
}
EXPECTED_MULTIPLE = {
    ("A128c", 8), ("A128c", 10), ("A128r", 8), ("A128r", 10),
    ("D1c", 10), ("D1c", 12), ("D1c", 14),
}


def run_json(args):
    result = subprocess.run(args, cwd=ROOT, check=True, capture_output=True,
                           text=True, timeout=900)
    return json.loads(result.stdout)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--counts", action="store_true",
                        help="run exact, KB, and IMPA count checks for every row")
    args = parser.parse_args()
    with CSV.open(newline="") as source:
        rows = list(csv.DictReader(source))
    girth = [r for r in rows if r["section"] == "Girth only"]
    multi = [r for r in rows if r["section"] == "Multiple cycle lengths"]
    assert len(rows) == 20 and len(girth) == 13 and len(multi) == 7
    assert {r["graph"] for r in girth} == EXPECTED_GIRTH_GRAPHS
    assert {(r["graph"], int(r["T"])) for r in multi} == EXPECTED_MULTIPLE

    checked = 0
    for row in rows:
        name, g, target = row["graph"], int(row["g"]), int(row["T"])
        graph = ROOT / "graphs" / f"{name}.edges"
        with graph.open() as source:
            n, m, edges = map(int, source.readline().split())
        assert n == int(row["n"]), (name, "n")
        assert edges // n == int(row["dv"]), (name, "dv")
        assert edges // m == int(row["dc"]), (name, "dc")

        expected = [int(x) for x in row["counts"].split(";")]
        targets = list(range(g, target + 1, 2))
        assert len(expected) == len(targets), (name, target, "count tuple")
        expected_map = {str(t): value for t, value in zip(targets, expected)}

        if args.counts:
            exact = run_json([str(ROOT / "counter"), str(graph), str(g),
                              str(target), "validate"])
            assert exact["canonical_dfs_agrees"]
            assert {t: exact["counts"][t] for t in expected_map} == expected_map
            kb = run_json([str(ROOT / "counter"), str(graph), str(g),
                           str(target), "bench"])
            assert kb["kb_agrees"]
            assert {t: kb["counts"][t] for t in expected_map} == expected_map

            impa = run_json([str(ROOT / "impa_count"), str(graph), str(g), str(target)])
            assert {t: impa["counts"][t] for t in expected_map} == expected_map

        if row["section"] == "Girth only":
            assert target == g
            assert row["Hybrid_ms"] and row["MARE_percent"]
        else:
            assert target > g
            assert row["Hybrid_ms"] == "" and row["MARE_percent"] == ""
        checked += 1

    print(f"Verified {checked}/20 table rows: row scope, graph metadata, and count tuple structure.")
    if args.counts:
        print("Exact, KB, and IMPA counts match all 20 table rows.")
    print("Timing fields are the rounded manuscript snapshot; this check does not certify historical timings.")


if __name__ == "__main__":
    main()
